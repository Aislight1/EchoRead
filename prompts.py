def get(key):
    """取模板 -> (system, user_template)。key 不存在直接抛错（写错 key 立刻暴露）。"""
    t = TEMPLATES[key]
    return t['system'], t['user']


def version_of(key):
    """模板版本号（如 'v1'）——消费方把它写进缓存 key 实现联动失效。"""
    return 'v' + str(TEMPLATES[key]['v'])


def fmt(key, **kwargs):
    """取模板并渲染 user。缺失占位符会在这里抛错（立刻暴露）。"""
    _s, u = get(key)
    return u.format(**kwargs)
